function switchLang(lang) {
    currentLang = lang;
    document.querySelectorAll('.lang-btn').forEach(btn => btn.classList.remove('active'));
    document.getElementById('btn' + lang.charAt(0).toUpperCase() + lang.slice(1))?.classList.add('active');
    document.getElementById('side' + lang.charAt(0).toUpperCase() + lang.slice(1))?.classList.add('active');
    document.getElementById('land' + lang.charAt(0).toUpperCase() + lang.slice(1))?.classList.add('active');
    updateTranslations();
    if (!document.getElementById('landingPage').classList.contains('hidden')) {
        // Landing page translations updated automatically
    } else if (!document.getElementById('guestMedicinesPage').classList.contains('hidden')) {
        renderGuestMedicines();
    } else if (!document.getElementById('guestCartPage').classList.contains('hidden')) {
        renderGuestCart();
    } else if (currentUser) {
        renderSidebar();
        renderPage();
    }
}

function updateTranslations() {
    const t = translations[currentLang];
    document.querySelectorAll('[data-key]').forEach(el => {
        const key = el.getAttribute('data-key');
        if (t[key]) el.textContent = t[key];
    });
}

function toggleDarkMode() {
    isDarkMode = !isDarkMode;
    document.documentElement.classList.toggle('dark', isDarkMode);
    localStorage.setItem('jasurmed_dark', isDarkMode);
    const icon = document.getElementById('darkModeIcon');
    if (icon) icon.className = isDarkMode ? 'fas fa-moon' : 'fas fa-sun';
}

