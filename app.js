async function uploadPrescriptionFile(file) {
    const ext = file.name.split('.').pop();
    const path = `rx_${Date.now()}_${Math.random().toString(36).slice(2)}.${ext}`;
    const { error } = await sb.storage.from('prescriptions').upload(path, file);
    if (error) { showNotification("Rasm yuklashda xato: " + error.message, 'danger'); return null; }
    const { data } = sb.storage.from('prescriptions').getPublicUrl(path);
    return data.publicUrl;
}

async function submitGuestOrder() {
    const t = translations[currentLang];
    const name = document.getElementById('checkoutName').value.trim();
    const phone = document.getElementById('checkoutPhone').value.trim();
    const lat = document.getElementById('checkoutLat').value;
    const lng = document.getElementById('checkoutLng').value;

    if (!name || !phone) {
        showNotification("Iltimos, barcha maydonlarni to'ldiring", 'warning');
        return;
    }
    if (!lat || !lng) {
        showNotification("Iltimos, xaritadan manzilni belgilang", 'warning');
        return;
    }

    const hasPrescription = cart.some(item => item.prescription);
    if (hasPrescription && !prescriptionImageFile) {
        showNotification("Retsept rasmini yuklang!", 'warning');
        return;
    }

    let prescriptionUrl = null;
    if (hasPrescription && prescriptionImageFile) {
        prescriptionUrl = await uploadPrescriptionFile(prescriptionImageFile);
        if (!prescriptionUrl) return;
    }

    const total = cart.reduce((sum, item) => sum + item.price * item.quantity, 0);
    const { data: newRow, error } = await sb.from('orders').insert({
        customer_id: currentUser ? currentSession?.user?.id : null,
        customer_name: name,
        phone: phone,
        items: JSON.parse(JSON.stringify(cart)),
        total,
        status: 'pending',
        prescription_status: hasPrescription ? 'pending' : 'approved',
        prescription_image: prescriptionUrl,
        address: "Lat: " + lat + ", Lng: " + lng,
        lat: parseFloat(lat), lng: parseFloat(lng),
        payment_method: 'cash'
    }).select().single();

    if (error) { showNotification("Buyurtma yuborilmadi: " + error.message, 'danger'); return; }

    const orderId = newRow.id;
    for (const item of cart) {
        const med = medicines.find(m => m.id === item.id);
        if (med) {
            const newStock = med.stock - item.quantity;
            await sb.from('medicines').update({ stock: newStock }).eq('id', item.id);
            med.stock = newStock;
        }
    }
    pushNotification('admin', null, 'Yangi buyurtma', `#${orderId} - ${name} (${total.toLocaleString()} so'm)`, orderId);
    pushNotification('farmatsevt', null, 'Yangi buyurtma', `#${orderId} - ${name} (${total.toLocaleString()} so'm)`, orderId);
    cart = [];
    prescriptionImageBase64 = null;
    prescriptionImageFile = null;
    updateGuestCartBadge();

    hideAllScreens();
    document.getElementById('landingPage').classList.remove('hidden');

    // Show success modal in landing
    const successDiv = document.createElement('div');
    successDiv.className = 'fixed inset-0 bg-black/50 z-[100] flex items-center justify-center p-4';
    successDiv.innerHTML = `
        <div class="bg-white dark:bg-gray-800 rounded-2xl p-8 max-w-md w-full text-center fade-in">
            <div class="w-20 h-20 bg-success/10 rounded-full flex items-center justify-center mx-auto mb-6">
                <i class="fas fa-check text-success text-3xl"></i>
            </div>
            <h2 class="text-2xl font-bold text-secondary dark:text-white mb-2">${t.orderSuccess}</h2>
            <p class="text-gray-500 mb-2">${t.orderNumber}: <span class="font-bold text-primary">#${orderId}</span></p>
            ${hasPrescription ? `<p class="text-sm text-warning mb-4"><i class="fas fa-clock mr-1"></i>Retseptingiz farmatsevt tasdig'ini kutyapti</p>` : ''}
            <p class="text-sm text-gray-400 mb-6">To'lov usuli: Naqd pul (yetkazib berilganda)</p>
            <button onclick="this.closest('.fixed').remove()" class="bg-primary text-white px-6 py-3 rounded-xl font-medium hover:bg-primary/90">${t.backHome}</button>
        </div>
    `;
    document.body.appendChild(successDiv);
    showNotification(t.orderSuccess, 'success');
    if (hasPrescription) sendBrowserNotification('Yangi retseptli buyurtma', `Buyurtma #${orderId} retsept tekshiruvini kutmoqda`);
}

