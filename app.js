function initCheckoutMap() {
    if (checkoutMap) { checkoutMap.remove(); }
    // Default: Tashkent center
    checkoutMap = L.map('map').setView([41.2995, 69.2401], 13);
    L.tileLayer('https://{s}.tile.openstreetmap.org/{z}/{x}/{y}.png', {
        attribution: '&copy; OpenStreetMap'
    }).addTo(checkoutMap);

    checkoutMarker = L.marker([41.2995, 69.2401], { draggable: true }).addTo(checkoutMap);

    checkoutMarker.on('dragend', function() {
        const pos = checkoutMarker.getLatLng();
        document.getElementById('checkoutLat').value = pos.lat;
        document.getElementById('checkoutLng').value = pos.lng;
        document.getElementById('checkoutAddress').value = "Lat: " + pos.lat.toFixed(4) + ", Lng: " + pos.lng.toFixed(4);
    });

    checkoutMap.on('click', function(e) {
        checkoutMarker.setLatLng(e.latlng);
        document.getElementById('checkoutLat').value = e.latlng.lat;
        document.getElementById('checkoutLng').value = e.latlng.lng;
        document.getElementById('checkoutAddress').value = "Lat: " + e.latlng.lat.toFixed(4) + ", Lng: " + e.latlng.lng.toFixed(4);
    });

    // Try geolocation
    if (navigator.geolocation) {
        navigator.geolocation.getCurrentPosition(pos => {
            const lat = pos.coords.latitude;
            const lng = pos.coords.longitude;
            checkoutMap.setView([lat, lng], 15);
            checkoutMarker.setLatLng([lat, lng]);
            document.getElementById('checkoutLat').value = lat;
            document.getElementById('checkoutLng').value = lng;
            document.getElementById('checkoutAddress').value = "Lat: " + lat.toFixed(4) + ", Lng: " + lng.toFixed(4);
        }, () => {});
    }
}

