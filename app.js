function updateGuestCartQty(idx, delta) {
    const item = cart[idx];
    const med = medicines.find(m => m.id === item.id);
    const newQty = item.quantity + delta;
    if (newQty < 1) removeFromGuestCart(idx);
    else if (newQty > med.stock) showNotification("Omborda yetarli emas!", 'warning');
    else { item.quantity = newQty; renderGuestCart(); }
}

function removeFromGuestCart(idx) {
    cart.splice(idx, 1);
    updateGuestCartBadge();
    renderGuestCart();
}

function clearGuestCart() {
    cart = [];
    prescriptionImageBase64 = null;
    updateGuestCartBadge();
    renderGuestCart();
}

