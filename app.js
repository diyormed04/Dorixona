function mapMedicine(r) {
    return { id: r.id, name: { lotin: r.name_lotin, kril: r.name_kril }, category: r.category, price: r.price, stock: r.stock, prescription: r.prescription, manufacturer: r.manufacturer, expiry: r.expiry, description: { lotin: r.description_lotin, kril: r.description_kril } };
}
function medicineToRow(m) {
    return { name_lotin: m.name.lotin, name_kril: m.name.kril, category: m.category, price: m.price, stock: m.stock, prescription: m.prescription, manufacturer: m.manufacturer, expiry: m.expiry, description_lotin: m.description.lotin, description_kril: m.description.kril };
}
function mapOrder(r) {
    return { id: r.id, customerId: r.customer_id, customerName: r.customer_name, phone: r.phone, items: r.items, total: r.total, status: r.status, prescriptionStatus: r.prescription_status, prescriptionImage: r.prescription_image, date: r.created_at, address: r.address, lat: r.lat, lng: r.lng, courierId: r.courier_id, paymentMethod: r.payment_method, availableItems: r.available_items || null };
}
function mapFaq(r) {
    return { id: r.id, question: { lotin: r.question_lotin, kril: r.question_kril }, answer: { lotin: r.answer_lotin, kril: r.answer_kril } };
}
function mapCategory(r) {
    return { id: r.id, builtin: r.builtin, name: r.builtin ? null : { lotin: r.name_lotin, kril: r.name_kril } };
}
function mapPharmacyInfo(r) {
    return { name: "Jasur Med", address: { lotin: r.address_lotin, kril: r.address_kril }, phone: r.phone, email: r.email, workingHours: { lotin: r.hours_lotin, kril: r.hours_kril }, about: { lotin: r.about_lotin, kril: r.about_kril } };
}

async function loadPublicData() {
    const [medRes, catRes, faqRes, infoRes] = await Promise.all([
        sb.from('medicines').select('*').order('id'),
        sb.from('categories').select('*'),
        sb.from('faq').select('*').order('id'),
        sb.from('pharmacy_info').select('*').eq('id', 1).single()
    ]);
    medicines = (medRes.data || []).map(mapMedicine);
    if (catRes.data && catRes.data.length) categories = catRes.data.map(mapCategory);
    faqData = (faqRes.data || []).map(mapFaq);
    if (infoRes.data) pharmacyInfo = mapPharmacyInfo(infoRes.data);
}

async function loadStaffData() {
    const [ordRes, profRes] = await Promise.all([
        sb.from('orders').select('*').order('id', { ascending: false }),
        sb.from('profiles').select('*').order('name')
    ]);
    orders = (ordRes.data || []).map(mapOrder);
    credentials = profRes.data || [];
}

async function loadOrderChat(orderId) {
    const { data } = await sb.from('chat_messages').select('*').eq('order_id', orderId).order('created_at');
    chatData[orderId] = (data || []).map(m => ({ from: m.sender_email, text: m.text, time: new Date(m.created_at).toLocaleTimeString('uz-UZ', { hour: '2-digit', minute: '2-digit' }) }));
}

