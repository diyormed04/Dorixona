async function saveMedicine(medId) {
    const nameLotin = document.getElementById('medNameLotin').value;
    const nameKril = document.getElementById('medNameKril').value;
    const price = parseInt(document.getElementById('medPrice').value) || 0;
    const stock = parseInt(document.getElementById('medStock').value) || 0;
    const category = document.getElementById('medCat').value;
    const prescription = document.getElementById('medPrescription').checked;
    if (!nameLotin || !nameKril) { showNotification("Barcha maydonlarni to'ldiring!", 'warning'); return; }
    const row = { name_lotin: nameLotin, name_kril: nameKril, category, price, stock, prescription, manufacturer: "Jasur Med", expiry: "2027-12", description_lotin: "Yangi dori", description_kril: "Янги дори" };
    if (medId) {
        const { error } = await sb.from('medicines').update(row).eq('id', medId);
        if (error) { showNotification("Xatolik: " + error.message, 'danger'); return; }
        const med = medicines.find(m => m.id === medId);
        med.name = { lotin: nameLotin, kril: nameKril };
        med.price = price; med.stock = stock; med.category = category; med.prescription = prescription;
    } else {
        const { data, error } = await sb.from('medicines').insert(row).select().single();
        if (error) { showNotification("Xatolik: " + error.message, 'danger'); return; }
        medicines.push(mapMedicine(data));
    }
    closeModal(); renderPage();
    showNotification(translations[currentLang].save + " ✓", 'success');
}

async function deleteMedicine(medId) {
    if (confirm("O'chirishni tasdiqlaysizmi?")) {
        const { error } = await sb.from('medicines').delete().eq('id', medId);
        if (error) { showNotification("Xatolik: " + error.message, 'danger'); return; }
        medicines = medicines.filter(m => m.id !== medId);
        renderPage();
        showNotification(translations[currentLang].delete + " ✓", 'success');
    }
}

